// Copies Moorhen Squab's TypeScript helpers and data tables into npm/src so tsc can
// compile them into the package. The originals stay the single source of
// truth; everything written here is generated and gitignored.
//
//   ../src/utils/*.ts, ../src/types/*.ts      -> src/vendor/{utils,types}/
//   ../frontend/src/webgpu/DebyeGPU.ts        -> src/vendor/webgpu/DebyeGPU.ts
//   ../frontend/public/*.json, *.wgsl         -> src/generated/assets.ts (as strings)

import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const npmDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(npmDir, "..");

const header = (from) =>
    `// GENERATED by npm/scripts/prepare-sources.mjs from ${from}\n` +
    `// Do not edit here: edit the original in MoorhenSquab and rebuild.\n`;

function need(path) {
    if (!existsSync(path)) {
        throw new Error(`Expected MoorhenSquab file is missing: ${path}`);
    }
    return readFileSync(path, "utf8");
}

// ------------------------------------------------------------- vendor TS
const vendorDir = join(npmDir, "src", "vendor");
rmSync(vendorDir, { recursive: true, force: true });

const vendored = [
    ["src/utils/SAXSScaling.ts", "utils/SAXSScaling.ts"],
    ["src/utils/SAXSProfileParser.ts", "utils/SAXSProfileParser.ts"],
    ["src/utils/DebyeReference.ts", "utils/DebyeReference.ts"],
    ["src/types/SAXSProfile.ts", "types/SAXSProfile.ts"],
    ["src/types/SAXSComparison.ts", "types/SAXSComparison.ts"],
    // DebyeGPU.ts lives in the Vite app and isn't type-clean on its own
    // (reducePipeline is never declared), so it is compiled unchecked.
    ["frontend/src/webgpu/DebyeGPU.ts", "webgpu/DebyeGPU.ts", "// @ts-nocheck\n"],
];

for (const [from, to, prefix = ""] of vendored) {
    const out = join(vendorDir, to);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, prefix + header(from) + need(join(repo, from)));
}

// ------------------------------------------------------------- assets
const assets = {
    elementsInfoJson: "frontend/public/elementsInfo.json",
    saxsAtomTypesJson: "frontend/public/SAXSAtomTypes.json",
    residueAtomTypesJson: "frontend/public/residueAtomTypes.json",
    debyeWgsl: "frontend/public/debye.wgsl",
    reduceWgsl: "frontend/public/reduce.wgsl",
};

let assetSource = header(Object.values(assets).join(", "));
for (const [name, from] of Object.entries(assets)) {
    assetSource += `export const ${name}: string = ${JSON.stringify(need(join(repo, from)))};\n`;
}

const generatedDir = join(npmDir, "src", "generated");
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(generatedDir, "assets.ts"), assetSource);

console.log("prepare-sources: vendored", vendored.length, "TS files and", Object.keys(assets).length, "assets");
